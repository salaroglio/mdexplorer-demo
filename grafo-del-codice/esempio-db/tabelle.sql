-- Le tabelle dell'help desk di Alpina Servizi (inventate).
CREATE TABLE OPERATORE (
  ID      NUMBER PRIMARY KEY,
  NOME    VARCHAR2(100) NOT NULL,
  ATTIVO  NUMBER(1) DEFAULT 1
);

CREATE TABLE TICKET (
  ID            NUMBER PRIMARY KEY,
  STATO         VARCHAR2(20),
  SETTIMANA     NUMBER,
  OPERATORE_ID  NUMBER REFERENCES OPERATORE(ID)
);

CREATE TABLE STORICO_RAPPORTI (
  SETTIMANA  NUMBER,
  TICKET     NUMBER,
  CHIUSO_IL  DATE
);

CREATE OR REPLACE VIEW V_TICKET_APERTI AS
  SELECT T.ID, T.SETTIMANA, O.NOME
    FROM TICKET T
    JOIN OPERATORE O ON O.ID = T.OPERATORE_ID
   WHERE T.STATO <> 'CHIUSO';
